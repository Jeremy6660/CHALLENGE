# ── 数据流 ──
st.subheader("🔄 数据流详解")

st.markdown("""
```
1. API Gateway 接收请求 (elderly_id + context_data)
   │
2. Context Builder 从数据库组装老人全维数据
   │
3. 4个评估Agent并行调用 (asyncio.gather, 独立LLM call)
   │  每个Agent返回结构化JSON (Pydantic验证)
   │
4. Orchestrator 消费 4 份报告:
   ├── a. 提取所有干预建议 → 原始干预池
   ├── b. 规则引擎检测跨域冲突 → 硬编码消解
   ├── c. LLM深层编排 → 柔性冲突消解
   ├── d. 优先级排序 (安全>医疗>护理>社工>餐饮)
   └── e. 生成统一干预计划
   │
5. Decision Agent 审核计划:
   ├── a. 合理性审核 (是否遗漏关键风险点)
   ├── b. 安全性审核 (干预与用药/疾病是否矛盾)
   ├── c. 资源可行性审核 (人力/设备/费用)
   └── d. 输出: PASS → 最终计划 / REVISE → 带修改建议 / REJECT → 打回重做
   │
6. 渲染输出:
   ├── 📋 综合干预计划 (三级优先级: 紧急/本周内/持续)
   ├── ⚠️ 风险预警清单
   ├── 💬 家属沟通叙事报告
   └── 📝 管理层执行摘要
```
""")

